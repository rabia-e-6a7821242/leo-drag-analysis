"""
run_scenarios.py
Builds Fortran namelist files for every experiment, runs the orbit_decay
executable for each of them and collects the lifetimes in a summary table.

Run from the repository root:
    python3 python/run_scenarios.py
"""

import csv
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXE = ROOT / "bin" / "orbit_decay"
RUN_DIR = ROOT / "runs"
DATA_DIR = ROOT / "results" / "data"

# ---------------------------------------------------------------------------
# Baseline satellite / run settings (shared by all cases)
# A ~150 kg small satellite with two deployable sun-tracking solar wings.
# ---------------------------------------------------------------------------
BASE = {
    "satellite": {
        "mass_kg": 150.0,
        "cd": 2.2,
        "area_body": 0.6,
        "area_panel": 2.4,
        "area_mode": "fixed_avg",
        "beta_amp_deg": 0.0,
        "beta_period_day": 60.0,
    },
    "orbit": {"h0_km": 500.0, "h_end_km": 150.0},
    "environment": {
        "density_model": "sws",
        "solar_mode": "constant",
        "f107_const": 150.0,
        "f107_min": 70.0,
        "f107_max": 220.0,
        "cycle_length_yr": 11.0,
        "cycle_phase_yr": 0.0,
        "ap_quiet": 15.0,
        "storm_start_day": -1.0,
        "storm_length_day": 0.0,
        "storm_ap": 200.0,
    },
    "run": {"dt_s": 60.0, "out_dt_s": 21600.0, "t_max_day": 9131.0},  # 25 years
}

SOLAR_LEVELS = {"low": 70.0, "moderate": 150.0, "high": 230.0}


def make_case(name, group, **changes):
    """Copy the baseline and overwrite the given keys (key names are unique
    across namelist groups, so we just look them up)."""
    cfg = {g: dict(v) for g, v in BASE.items()}
    for key, value in changes.items():
        for g in cfg:
            if key in cfg[g]:
                cfg[g][key] = value
                break
        else:
            raise KeyError(f"unknown parameter {key}")
    return {"name": name, "group": group, "cfg": cfg}


def build_cases():
    cases = []

    # 1) Solar activity: constant F10.7 levels + static (no solar) reference
    for level, f107 in SOLAR_LEVELS.items():
        cases.append(make_case(f"solar_{level}", "solar", f107_const=f107))
    cases.append(make_case("solar_static_model", "solar", density_model="static"))

    # 2) Idealised 11-year solar cycle, launched at minimum vs. at maximum
    cases.append(make_case("cycle_launch_at_min", "cycle",
                           solar_mode="cycle", cycle_phase_yr=0.0))
    cases.append(make_case("cycle_launch_at_max", "cycle",
                           solar_mode="cycle", cycle_phase_yr=5.5))

    # 3) Geomagnetic storm (Ap = 200 for 3 days) vs. quiet baseline
    cases.append(make_case("storm_none", "storm", h0_km=400.0))
    cases.append(make_case("storm_3day", "storm", h0_km=400.0,
                           storm_start_day=20.0, storm_length_day=3.0))

    # 4) Frontal area assumption x solar activity
    for level, f107 in SOLAR_LEVELS.items():
        for mode in ("fixed_max", "fixed_avg", "varying"):
            cases.append(make_case(f"area_{mode}_{level}", "area",
                                   area_mode=mode, f107_const=f107))
    # time-varying area with a precessing beta angle (beta up to 60 deg)
    for level, f107 in SOLAR_LEVELS.items():
        cases.append(make_case(f"area_varying_beta60_{level}", "area",
                               area_mode="varying", beta_amp_deg=60.0,
                               f107_const=f107))
    return cases


def fmt(value):
    if isinstance(value, str):
        return f"'{value}'"
    return f"{value:g}"


def write_namelist(case, path):
    lines = [f"! auto-generated by run_scenarios.py, case: {case['name']}"]
    for group, params in case["cfg"].items():
        lines.append(f"&{group}")
        for key, value in params.items():
            lines.append(f"  {key} = {fmt(value)}")
        lines.append("/")
    path.write_text("\n".join(lines) + "\n")


def parse_summary(stdout):
    out = {}
    for line in stdout.splitlines():
        if "=" in line:
            key, value = (s.strip() for s in line.split("=", 1))
            out[key] = value
    return out


def main():
    if not EXE.exists():
        raise SystemExit("orbit_decay not found, run `make` first")
    RUN_DIR.mkdir(exist_ok=True)
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    rows = []
    for case in build_cases():
        nml = RUN_DIR / f"{case['name']}.nml"
        out = DATA_DIR / f"{case['name']}.csv"
        write_namelist(case, nml)
        res = subprocess.run([str(EXE), str(nml), str(out)],
                             capture_output=True, text=True, check=True)
        s = parse_summary(res.stdout)
        sat, env = case["cfg"]["satellite"], case["cfg"]["environment"]
        rows.append({
            "case": case["name"],
            "group": case["group"],
            "h0_km": case["cfg"]["orbit"]["h0_km"],
            "density_model": env["density_model"],
            "solar_mode": env["solar_mode"],
            "f107": env["f107_const"] if env["solar_mode"] == "constant" else "cycle",
            "area_mode": sat["area_mode"],
            "beta_amp_deg": sat["beta_amp_deg"],
            "reentered": s["REENTERED"] == "T",
            "lifetime_days": float(s["LIFETIME_DAYS"]),
        })
        status = "re-entry" if rows[-1]["reentered"] else "still in orbit"
        print(f"{case['name']:<30s} {rows[-1]['lifetime_days']:9.1f} days  ({status})")

    with open(ROOT / "results" / "summary.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    print("\nsummary written to results/summary.csv")


if __name__ == "__main__":
    main()
